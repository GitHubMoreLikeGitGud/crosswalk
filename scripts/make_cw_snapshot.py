"""The SEC submissions snapshot cw.seed_submissions_snapshot (decision D15): one read of cw.seed_utilities at
onboarding, kept as a cached SchemaStore VALUES view so that the question path never reads cw.seed_utilities
(the UNION of the 43 submission views, about 17 s per statement because the 43 views are resolved on every
read, cached or not).

    python scripts/make_cw_snapshot.py                 # render the SQL pair and the manifest entry from the snapshot file
    python scripts/make_cw_snapshot.py --check         # exit 1 if a committed file differs from what the snapshot file gives
    python scripts/make_cw_snapshot.py --apply         # make sure the view exists in Zetaris (DESCRIBE; CREATE + CACHE when absent)
    python scripts/make_cw_snapshot.py --read --apply  # refresh: read cw.seed_utilities once, rewrite, CREATE OR REPLACE, re-cache

Inputs and outputs (deterministic: the same snapshot file gives the same bytes):
- zetaris/snapshots/seed_submissions_snapshot.json: the rows read (cik10, name, ticker, sic, hq_state), the source
  statement, its execution time (snapshot_at, UTC) and its elapsed ms; written only by --read;
- zetaris/sql/10_cw_seed_snapshot_create.sql and _select.sql, rendered from that file;
- the cw_seed_snapshot entry of zetaris/manifest.json (source statement and snapshot time), rendered from it.
Every statement passes the gateway's onboard allowlist and is logged to data/evidence/sql_log.jsonl. The last
line printed is a JSON summary that `npm run onboard` reads.
"""

from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

SNAPSHOT_FILE = ROOT / "zetaris" / "snapshots" / "seed_submissions_snapshot.json"
CREATE_SQL = ROOT / "zetaris" / "sql" / "10_cw_seed_snapshot_create.sql"
SELECT_SQL = ROOT / "zetaris" / "sql" / "10_cw_seed_snapshot_select.sql"
MANIFEST = ROOT / "zetaris" / "manifest.json"
VIEW = "cw.seed_submissions_snapshot"
SOURCE_STATEMENT = "SELECT cik, name, ticker, sic, hq_state FROM cw.seed_utilities ORDER BY cik"
COLUMNS = ("cik10", "name", "ticker", "sic", "hq_state")
ENTRY_ID = "cw_seed_snapshot"


def _literal(value) -> str:
    if value is None:
        return "CAST(NULL AS STRING)"
    s = str(value)
    if "'" in s or "\\" in s:
        raise ValueError(f"snapshot value needs escaping, refuse to guess: {s!r}")
    return f"'{s}'"


def load_snapshot() -> dict:
    snap = json.loads(SNAPSHOT_FILE.read_text(encoding="utf-8"))
    if snap.get("columns") != list(COLUMNS):
        raise ValueError(f"{SNAPSHOT_FILE.name}: columns must be {list(COLUMNS)}")
    ciks = [r[0] for r in snap["rows"]]
    if len(set(ciks)) != len(ciks) or not all(isinstance(c, str) and len(c) == 10 and c.isdigit() for c in ciks):
        raise ValueError(f"{SNAPSHOT_FILE.name}: every cik10 must be a distinct 10-digit string")
    return snap


def create_sql(snap: dict, replace: bool = False) -> str:
    rows = [f"    ({', '.join(_literal(v) for v in r)}, {_literal(snap['snapshot_at'])})" for r in snap["rows"]]
    head = "CREATE OR REPLACE SCHEMASTORE VIEW" if replace else "CREATE SCHEMASTORE VIEW"
    return "\n".join([
        "-- =============================================================================",
        "-- Source: SEC EDGAR submissions profiles of the 43 seed utilities, as the cached",
        "-- view cw.seed_utilities serves them (05_cw_seeds_create.sql: the UNION of the 43",
        "-- cached cw.submission_<cik10> views plus the seed ticker), read ONCE at",
        "-- onboarding with the statement below and kept as inline VALUES:",
        f"--   {snap['source_statement']}",
        f"--   executed {snap['snapshot_at']} ({snap['rows_read']} rows, {snap['elapsed_ms']} ms)",
        "-- Generated by scripts/make_cw_snapshot.py from zetaris/snapshots/",
        "-- seed_submissions_snapshot.json; regenerate rather than hand-edit.",
        "-- Licence: SEC EDGAR submissions are public US government data; only profile",
        "-- fields are kept (cik, name, ticker, SIC, business-address state), no XBRL facts.",
        "-- Format: CREATE SCHEMASTORE VIEW ... AS SELECT ... FROM VALUES (...) AS t(...),",
        "-- the shape of 05_cw_seeds_create.sql; every row carries snapshot_at.",
        "-- Rate limit: none (no source call).",
        "-- Why (decision D15): the question path reads this view (sub-second) instead of",
        "-- cw.seed_utilities, which resolves the 43 submission views on every read",
        "-- (about 17 s per statement, 2026-10-25). A refresh is explicit:",
        "-- npm run onboard -- --refresh-snapshot (CREATE OR REPLACE, then re-cache).",
        "-- Status and counts: ../README.md.",
        "-- =============================================================================",
        "",
        "-- Step 1: one row per seed utility, ordered by cik10.",
        f"{head} seed_submissions_snapshot WITH CONTAINER cw AS",
        f"SELECT {', '.join(COLUMNS)}, snapshot_at FROM VALUES",
        ",\n".join(rows),
        f"  AS t({', '.join(COLUMNS)}, snapshot_at);",
        "",
        "-- Step 2: cache it (gateway.app.CACHE_TARGETS keeps it cached after a driver restart).",
        f"CACHE TABLE {VIEW};",
        "",
        "-- Next: verify with 10_cw_seed_snapshot_select.sql",
        "",
    ])


def select_sql(snap: dict) -> str:
    rows = snap["rows"]
    sics = sorted({r[3] for r in rows})
    with_ticker = sum(1 for r in rows if r[2] not in (None, ""))
    return "\n".join([
        "-- =============================================================================",
        "-- Verification for 10_cw_seed_snapshot_create.sql. Every statement reads cached",
        "-- views (sub-second); the expected values are the snapshot file's.",
        "-- =============================================================================",
        "",
        f"-- 1. Rows, distinct CIKs, tickers present, SIC codes, snapshot times: {len(rows)}, {len(rows)}, {with_ticker}, {len(sics)}, 1.",
        f"SELECT COUNT(*) AS n, COUNT(DISTINCT cik10) AS ciks, COUNT(NULLIF(ticker, '')) AS with_ticker, COUNT(DISTINCT sic) AS sic_codes, COUNT(DISTINCT snapshot_at) AS snapshots FROM {VIEW};",
        "",
        "-- 2. Every seed utility of cw.seed_utility_names is in the snapshot with the same SIC.",
        f"SELECT COUNT(*) AS named, COUNT(s.cik10) AS in_snapshot, COUNT(CASE WHEN s.sic = n.sic THEN 1 END) AS same_sic FROM cw.seed_utility_names n LEFT JOIN {VIEW} s ON s.cik10 = n.cik;",
        "",
        "-- 3. The SIC the company_dns reference lacks (MGE Energy, 4900).",
        f"SELECT cik10, name, ticker, sic, hq_state FROM {VIEW} WHERE sic = '4900';",
        "",
    ])


def manifest_entry(snap: dict) -> dict:
    rows = snap["rows"]
    return {
        "id": ENTRY_ID,
        "kind": "values-views",
        "script": "zetaris/sql/10_cw_seed_snapshot_create.sql",
        "select": "zetaris/sql/10_cw_seed_snapshot_select.sql",
        "status": "verified",
        "requires": ["cw_seeds"],
        "hosts": [],
        "summary": (f"cw.seed_submissions_snapshot: the SEC submissions profile of the {len(rows)} seed utilities (cik10, name, ticker, "
                    f"sic, hq_state, snapshot_at) read once from cw.seed_utilities at onboarding and kept as a cached VALUES view "
                    f"(scripts/make_cw_snapshot.py); the question path's probe and the cik, loc, sic and control join-map statements "
                    f"read it instead of cw.seed_utilities (decision D15)"),
        "snapshot": {
            "source_statement": snap["source_statement"],
            "snapshot_at": snap["snapshot_at"],
            "rows": len(rows),
            "read_elapsed_ms": snap["elapsed_ms"],
            "file": "zetaris/snapshots/seed_submissions_snapshot.json",
        },
        "objects": {"container": "cw", "views": [VIEW]},
    }


def _dump(value, indent: int = 0) -> str:
    """JSON in the manifest's layout: two-space indent, lists of scalars on one line."""
    pad = "  " * indent
    if isinstance(value, dict):
        if not value:
            return "{}"
        items = [f'{pad}  {json.dumps(k, ensure_ascii=False)}: {_dump(v, indent + 1)}' for k, v in value.items()]
        return "{\n" + ",\n".join(items) + f"\n{pad}}}"
    if isinstance(value, list):
        if all(not isinstance(x, (dict, list)) for x in value):
            return "[" + ", ".join(json.dumps(x, ensure_ascii=False) for x in value) + "]"
        items = [f"{pad}  {_dump(x, indent + 1)}" for x in value]
        return "[\n" + ",\n".join(items) + f"\n{pad}]"
    return json.dumps(value, ensure_ascii=False)


def manifest_text(snap: dict) -> str:
    data = json.loads(MANIFEST.read_text(encoding="utf-8"))
    entry = manifest_entry(snap)
    sources = [s for s in data["sources"] if s.get("id") != ENTRY_ID]
    data["sources"] = sources + [entry]
    return _dump(data) + "\n"


def render_files() -> dict[Path, str]:
    snap = load_snapshot()
    return {CREATE_SQL: create_sql(snap), SELECT_SQL: select_sql(snap), MANIFEST: manifest_text(snap)}


# ---------------------------------------------------------------- live (JDBC, onboard allowlist, logged)

def _connection():
    from gateway.jdbc import LightningConnection, load_env
    load_env()
    return LightningConnection.from_env("admin")


def _run(conn, sql: str, timeout_s: float = 600.0):
    from gateway import allowlist
    from gateway.sqllog import log_statement, sha256
    allowlist.check(sql, "onboard")
    entry = {"source_file": "scripts/make_cw_snapshot.py", "role": "onboard", "sql": sql, "sql_sha256": sha256(sql), "timeout_s": timeout_s}
    try:
        res = conn.execute(sql, timeout_s=timeout_s)
        entry.update(elapsed_ms=res.elapsed_ms, row_count=res.row_count, executed_at=res.executed_at, error=None)
        return res
    except Exception as e:  # logged, then raised
        entry.update(error=str(e)[:1000])
        raise
    finally:
        log_statement(entry)


def read_live(conn) -> dict:
    res = _run(conn, SOURCE_STATEMENT, timeout_s=120.0)
    cols = [c.lower() for c in res.columns]
    want = ("cik", "name", "ticker", "sic", "hq_state")
    idx = [cols.index(c) for c in want]
    rows = [[None if r[i] is None else str(r[i]) for i in idx] for r in res.rows]
    snap = {
        "source_statement": SOURCE_STATEMENT,
        "snapshot_at": res.executed_at,
        "elapsed_ms": res.elapsed_ms,
        "rows_read": len(rows),
        "columns": list(COLUMNS),
        "rows": sorted(rows, key=lambda r: r[0]),
    }
    SNAPSHOT_FILE.parent.mkdir(parents=True, exist_ok=True)
    SNAPSHOT_FILE.write_text(json.dumps(snap, indent=2, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")
    return snap


def view_exists(conn) -> bool:
    from gateway.jdbc import ZetarisError
    try:
        _run(conn, f"DESCRIBE {VIEW}", timeout_s=60.0)
        return True
    except ZetarisError:
        return False


def apply(conn, refreshed: bool) -> dict:
    from gateway.jdbc import split_statements
    snap = load_snapshot()
    statements: list[dict] = []
    exists = view_exists(conn)
    if exists and not refreshed:
        return {"status": "already_registered", "statements": statements}
    sql = create_sql(snap, replace=exists)
    parts = split_statements(sql)
    if exists:
        parts = [parts[0], f"UNCACHE TABLE {VIEW}", parts[1]]
    for s in parts:
        t0 = time.perf_counter()
        res = _run(conn, s)
        statements.append({"sql": " ".join(s.split())[:120], "elapsed_ms": res.elapsed_ms, "wall_ms": round((time.perf_counter() - t0) * 1000)})
    return {"status": "refreshed" if exists else "registered", "statements": statements}


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--check", action="store_true", help="compare the committed files with what the snapshot file gives")
    p.add_argument("--read", action="store_true", help="read cw.seed_utilities once and rewrite the snapshot file (a refresh)")
    p.add_argument("--apply", action="store_true", help="make sure the view exists in Zetaris (and replace it after --read)")
    args = p.parse_args(argv)
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    if args.check:
        bad = 0
        for path, text in render_files().items():
            same = path.exists() and path.read_text(encoding="utf-8") == text
            print(f"{path.relative_to(ROOT).as_posix()}: {'ok' if same else 'DIFFERS'}")
            bad += not same
        return 1 if bad else 0
    summary: dict = {"view": VIEW, "read": None, "status": "rendered"}
    conn = _connection() if (args.read or args.apply or not SNAPSHOT_FILE.exists()) else None
    try:
        if args.read or not SNAPSHOT_FILE.exists():
            t0 = time.perf_counter()
            snap = read_live(conn)
            summary["read"] = {"sql": SOURCE_STATEMENT, "rows": snap["rows_read"], "elapsed_ms": snap["elapsed_ms"],
                               "wall_ms": round((time.perf_counter() - t0) * 1000), "snapshot_at": snap["snapshot_at"]}
        for path, text in render_files().items():
            path.write_text(text, encoding="utf-8", newline="\n")
        if args.apply:
            summary.update(apply(conn, refreshed=summary["read"] is not None))
    finally:
        if conn is not None:
            conn.close()
    snap = load_snapshot()
    summary.update(snapshot_at=snap["snapshot_at"], rows=len(snap["rows"]))
    print(json.dumps(summary, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
