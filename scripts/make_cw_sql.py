"""Write the generated Zetaris SQL files from the committed seeds (deterministic: same seeds, same bytes).

    python scripts/make_cw_sql.py            # writes both files
    python scripts/make_cw_sql.py --check    # exit 1 if a committed file differs from what the seeds give

zetaris/sql/08_cw_seed_names_create.sql: the SchemaStore VALUES view cw.seed_utility_names (cik as a 10-digit
string, name, ticker, sic) from seeds/utilities.json, then CACHE. The answer path reads it instead of
cw.seed_utilities (which resolves the 43 submission views on every read, about 17 s).

zetaris/sql/09_cw_ghcn_create.sql: the GHCN-Daily parquet tables CW_GHCN.ghcn_<year>_<element> for 2024 and 2025 x
TMAX, TMIN and their station-filtered views cw.ghcn_<year>_<element>, rendered from the gateway's register_ghcn
templates (gateway/templates.py), so the file and the registrar plan send the same statements.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from gateway import templates  # noqa: E402

SEED_NAMES_SQL = ROOT / "zetaris" / "sql" / "08_cw_seed_names_create.sql"
GHCN_SQL = ROOT / "zetaris" / "sql" / "09_cw_ghcn_create.sql"
GHCN_PAIRS = (("2025", "TMAX"), ("2025", "TMIN"), ("2024", "TMAX"), ("2024", "TMIN"))


def _literal(value: str | None) -> str:
    if value is None:
        return "CAST(NULL AS STRING)"
    if "'" in value or "\\" in value:
        raise ValueError(f"seed value needs escaping, refuse to guess: {value!r}")
    return f"'{value}'"


def seed_names_sql(utilities_path: Path = templates.SEEDS_PATH) -> str:
    utilities = json.loads(utilities_path.read_text(encoding="utf-8"))["utilities"]
    rows = [f"    ({_literal(u['cik'])}, {_literal(u['name'])}, {_literal(u.get('ticker'))}, {_literal(u['sic'])})"
            for u in sorted(utilities, key=lambda u: u["cik"])]
    return "\n".join([
        "-- =============================================================================",
        "-- Source: seeds/utilities.json of this repository (43 investor-owned electric",
        "-- utilities: CIK, name, ticker, SIC; curated from public SEC filings).",
        "-- Generated by scripts/make_cw_sql.py; regenerate rather than hand-edit.",
        "-- Licence: the seed file is this repository's own curated input (Apache-2.0).",
        "-- Format: CREATE SCHEMASTORE VIEW ... AS SELECT ... FROM VALUES (...) AS t(...),",
        "-- the shape of 05_cw_seeds_create.sql; a missing ticker is a typed NULL.",
        "-- Rate limit: none (no source call).",
        "-- Why: the answer path joins utility names and tickers from this view (sub-",
        "-- second) instead of cw.seed_utilities, which resolves the 43 cached submission",
        "-- views on every read (about 17 s per statement, 2026-10-25).",
        "-- Status and counts: ../README.md.",
        "-- =============================================================================",
        "",
        "-- Step 1: one row per seed utility, ordered by cik.",
        "CREATE SCHEMASTORE VIEW seed_utility_names WITH CONTAINER cw AS",
        "SELECT cik, name, ticker, sic FROM VALUES",
        ",\n".join(rows),
        "  AS t(cik, name, ticker, sic);",
        "",
        "-- Step 2: cache it (gateway.app.CACHE_TARGETS keeps it cached after a driver restart).",
        "CACHE TABLE cw.seed_utility_names;",
        "",
        "-- Next: verify with 08_cw_seed_names_select.sql",
        "",
    ])


def ghcn_sql() -> str:
    out = [
        "-- =============================================================================",
        "-- Source: NOAA Global Historical Climatology Network - Daily (GHCN-Daily),",
        "-- parquet partitions by year and element on the public AWS bucket:",
        "--   s3a://noaa-ghcn-pds/parquet/by_year/YEAR=<yyyy>/ELEMENT=<TMAX|TMIN>/",
        "-- One Lightning filestore table per (year, element): 2024 and 2025, TMAX and TMIN,",
        "-- each 9 parquet files with every station worldwide.",
        "-- Licence: CC0-1.0 (public domain), https://registry.opendata.aws/noaa-ghcn/",
        "-- Format: parquet FILESTORE table with the public-bucket options (no credentials);",
        "-- schema as inferred: ID, DATE yyyymmdd, DATA_VALUE (tenths of a degree C),",
        "-- M_FLAG, Q_FLAG, S_FLAG, OBS_TIME.",
        "-- Generated by scripts/make_cw_sql.py from the gateway's register_ghcn templates",
        "-- (gateway/templates.py): the same statements the registrar plan sends.",
        "-- Rate limit: none (anonymous S3). An uncached read scans the 9 files of a",
        "-- partition, so only the station-filtered views are read, and they are cached.",
        "-- Caveats:",
        f"--   1. The views keep the {len(templates.GHCN_STATIONS)} ids of seeds/stations.json plus {templates.VALIDATION_STATION}",
        "--      (Richmond, VA), the validation station of the degree-day check in",
        "--      09_cw_ghcn_select.sql. No seed utility uses it.",
        "--   2. The database CW_GHCN exists (02_cw_stations_create.sql); run with",
        "--      --skip-exists when the tables or views already exist.",
        "--   3. The raw tables are never cached (millions of rows each).",
        "-- Status and counts: ../README.md.",
        "-- =============================================================================",
    ]
    for step, suffix in ((1, "table"), (2, "view"), (3, "cache")):
        out += ["", {1: "-- Step 1: one filestore table per (year, element).",
                     2: "-- Step 2: station-filtered views, one per raw table, same columns.",
                     3: "-- Step 3: cache the views (each CACHE scans the 9 files of its partition once)."}[step]]
        for year, element in GHCN_PAIRS:
            _, sql = templates.render(f"registrar_ghcn_{suffix}", {"year": year, "element": element})
            out.append(sql + ";")
    out += ["", "-- Next: verify with 09_cw_ghcn_select.sql", ""]
    return "\n".join(out)


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--check", action="store_true", help="compare with the committed files instead of writing")
    args = p.parse_args()
    files = {SEED_NAMES_SQL: seed_names_sql(), GHCN_SQL: ghcn_sql()}
    bad = 0
    for path, text in files.items():
        if args.check:
            same = path.exists() and path.read_text(encoding="utf-8") == text
            print(f"{path.relative_to(ROOT).as_posix()}: {'ok' if same else 'DIFFERS'}")
            bad += not same
        else:
            path.write_text(text, encoding="utf-8", newline="\n")
            print(f"wrote {path.relative_to(ROOT).as_posix()}")
    return 1 if bad else 0


if __name__ == "__main__":
    raise SystemExit(main())
